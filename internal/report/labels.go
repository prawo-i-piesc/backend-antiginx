// LabelsFor zwraca etykiety dla języka; nieznany oznacza angielski.
func LabelsFor(lang Lang) *Labels {
	if lang == LangPL {
		return labelsPL
	}
	return labelsEN
}

func (l *Labels) Kind(kind string) string {
	if kind == KindPremium {
		return l.kindPremium
	}
	return l.kindFree
}

// StatusName tłumaczy status skanu; nieznany zostaje, jak przyszedł.
func (l *Labels) StatusName(status string) string {
	if name, ok := l.statuses[status]; ok {
		return name
	}
	return status
}

func (l *Labels) Severity(s Severity) string {
	if s < SeverityNone || s > SeverityCritical {
		s = SeverityInfo
	}
	return l.severities[s]
}

func (l *Labels) ResultOf(f Finding) string {
	if f.Passed {
		return l.resultPassed
	}
	return l.resultFailed
}

// Risk opisuje ogólną ocenę skanu jednym zwrotem.
func (l *Labels) Risk(s Summary) string {
	if s.Total == 0 {
		return l.noResults
	}
	if s.Failed == 0 {
		return l.noIssues
	}
	return l.risks[s.Risk]
}

func (l *Labels) GeneratedOn(doc Document) string {
	return fmt.Sprintf(l.generatedOn, formatTime(doc.GeneratedAt))
}

// Page to stopka strony PDF; total to alias liczby stron podstawiany przez fpdf.
func (l *Labels) Page(n int, total string) string {
	return fmt.Sprintf(l.page, n, total)
}
