// Lang to język etykiet raportu. Nazwy testów, komunikaty i metadane
// pochodzą z silnika i zostają po angielsku w każdym języku.
type Lang string

const (
	LangEN Lang = "en"
	LangPL Lang = "pl"
)

// Langs to języki w kolejności, w jakiej podaje je dokumentacja API.
var Langs = []Lang{LangEN, LangPL}

// ParseLang przyjmuje kod języka z zapytania, także z regionem ("pl-PL");
// pusty oznacza angielski.
func ParseLang(raw string) (Lang, bool) {
	code := strings.ToLower(strings.TrimSpace(raw))
	if i := strings.IndexAny(code, "-_"); i >= 0 {
		code = code[:i]
	}
	switch code {
	case "", "en":
		return LangEN, true
	case "pl":
		return LangPL, true
	}
	return "", false
}

